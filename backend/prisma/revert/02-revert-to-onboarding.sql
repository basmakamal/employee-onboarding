DELETE FROM `email_templates` WHERE `companyId` <> @main;
DELETE FROM `email_triggers`  WHERE `companyId` <> @main;
DELETE f FROM `sla_firings` f JOIN `sla_rules` r ON r.`id` = f.`ruleId` WHERE r.`companyId` <> @main;
DELETE FROM `sla_rules`       WHERE `companyId` <> @main;
-- branch-only holidays did not exist before; one holiday per date again
DELETE FROM `holidays`        WHERE `companyId` <> @main OR `orgUnitId` IS NOT NULL;

-- employee login accounts (switched off already) — the old system has no EMPLOYEE role
DELETE FROM `users` WHERE `role` = 'EMPLOYEE';

