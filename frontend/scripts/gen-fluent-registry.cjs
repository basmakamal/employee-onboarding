/**
 * Builds src/plugins/fluent-registry.ts from @iconify-json/fluent-color.
 *
 * The full set is 1.7 MB; the app uses a couple of dozen icons for
 * navigation and card headers, so only those are bundled. Add a name to
 * ICONS below and re-run:  node scripts/gen-fluent-registry.cjs
 */
const fs = require('node:fs');
const path = require('node:path');

const ICONS = [
  // navigation
  'home-24',
  'people-24',
  'mail-24',
  'data-trending-24',
  'bot-sparkle-24',
  'person-key-24',
  'people-team-24',
  'text-bullet-list-square-24',
  'clock-alarm-24',
  'mail-multiple-24',
  'calendar-24',
  'settings-24',
  // page / card headers
  'document-text-24',
  'clipboard-task-24',
  'document-folder-24',
  'toolbox-24',
  'certificate-24',
  'scan-person-24',
  'shield-checkmark-24',
  'person-starburst-24',
  'people-community-24',
  'briefcase-24',
  'receipt-24',
  'history-24',
  'form-24',
  'search-sparkle-24',
  'building-people-24',
  'checkmark-circle-24',
  'alert-24',
  'person-add-24',
  'people-list-24',
  'chat-24',
];

const set = require('@iconify-json/fluent-color/icons.json');
const out = [];
out.push('// AUTO-GENERATED by scripts/gen-fluent-registry.cjs — do not edit by hand.');
out.push('// Fluent Color icons (Microsoft, MIT) used for navigation and card headers.');
out.push('export interface FluentIcon { body: string; width: number; height: number }');
out.push('export const FLUENT_ICONS: Record<string, FluentIcon> = {');
for (const name of ICONS) {
  const icon = set.icons[name];
  if (!icon) {
    console.error(`missing icon: ${name}`);
    process.exitCode = 1;
    continue;
  }
  const width = icon.width ?? set.width ?? 24;
  const height = icon.height ?? set.height ?? 24;
  // The `-24` size suffix is an artefact of the source set; the app names icons without it.
  const key = name.replace(/-\d+$/, '');
  out.push(`  ${JSON.stringify(key)}: { width: ${width}, height: ${height}, body: ${JSON.stringify(icon.body)} },`);
}
out.push('};');
out.push('');

const target = path.join(__dirname, '..', 'src', 'plugins', 'fluent-registry.ts');
fs.writeFileSync(target, out.join('\n'));
console.log(`wrote ${ICONS.length} icons → ${path.relative(process.cwd(), target)}`);
